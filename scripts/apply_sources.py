"""Verify and apply the crawl sources in scripts/company_sources.json.

Source configs used to live only in D1. When the app was pointed at a new database they were
not carried over, and 28 companies quietly became "check by hand" -- including ones that had
crawled perfectly for weeks. This file is the record that survives a database change; the
database is a copy of it.

Usage:
    python scripts/apply_sources.py check [Company ...]   # crawl each source live, no writes
    python scripts/apply_sources.py sql out.sql           # UPDATE statements, keyed by name
    cd app && npx wrangler d1 execute job-search-os --remote --file ../out.sql

`check` runs the real adapters with the crawler's own HTTP client, so a source that passes here
is a source the scheduled crawl can read. It exits non-zero if any source fails or returns a
duplicate id.
"""

from __future__ import annotations

import asyncio
import json
import sys
from collections import Counter
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from crawler.adapters.registry import get_adapter  # noqa: E402
from crawler.http.client import CrawlBudget, HttpClient  # noqa: E402

SOURCES = Path(__file__).with_name("company_sources.json")


def load(only: set[str]) -> list[dict[str, Any]]:
    sources = json.loads(SOURCES.read_text())
    unknown = only - {s["name"] for s in sources}
    if unknown:
        sys.exit(f"not in {SOURCES.name}: {', '.join(sorted(unknown))}")
    return [s for s in sources if not only or s["name"] in only]


async def check(sources: list[dict[str, Any]]) -> int:
    failures = 0
    async with HttpClient() as http:
        for source in sources:
            adapter = get_adapter(source["source_type"])
            if adapter is None:
                print(f"FAIL {source['name']}: no adapter for {source['source_type']}")
                failures += 1
                continue
            errors = adapter.validate_config(source["config"])
            if errors:
                print(f"FAIL {source['name']}: {'; '.join(errors)}")
                failures += 1
                continue
            budget = CrawlBudget()
            budget.start()
            try:
                raws = await adapter.fetch_list(source["config"], http, budget)
            except Exception as exc:  # noqa: BLE001 - report every source, not just the first
                print(f"FAIL {source['name']}: {type(exc).__name__}: {str(exc)[:200]}")
                failures += 1
                continue
            jobs, parse_errors = [], 0
            for raw in raws:
                try:
                    jobs.append(adapter.parse(raw))
                except Exception:  # noqa: BLE001
                    parse_errors += 1
            repeats = sum(n - 1 for n in Counter(j.external_job_id for j in jobs).values())
            ok = parse_errors == 0 and repeats == 0 and (jobs or source["allow_zero_results"])
            failures += not ok
            print(
                f"{'ok  ' if ok else 'FAIL'} {source['name']}: {len(jobs)} jobs, "
                f"{parse_errors} parse errors, {repeats} repeated ids, {budget.used} requests"
            )
    return 1 if failures else 0


def _quote(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def sql(sources: list[dict[str, Any]]) -> str:
    lines = [f"-- Generated by scripts/apply_sources.py from {SOURCES.name}. Keyed by name."]
    for s in sources:
        # Health and conditional-request state describe the previous source, not this one.
        lines.append(
            "UPDATE companies SET "
            f"source_type = {_quote(s['source_type'])}, "
            f"source_tier = {int(s['source_tier'])}, "
            f"source_config = {_quote(json.dumps(s['config'], separators=(',', ':')))}, "
            f"careers_url = {_quote(s['careers_url'])}, "
            f"allow_zero_results = {1 if s['allow_zero_results'] else 0}, "
            "health_status = 'unknown', last_error = NULL, etag = NULL, "
            "last_modified = NULL, last_content_hash = NULL, "
            "updated_at = (unixepoch() * 1000) "
            f"WHERE name = {_quote(s['name'])};"
        )
    names = ", ".join(_quote(s["name"]) for s in sources)
    # A name that matched nothing updates nothing, silently; listing the result makes a
    # missing or misspelled company visible in wrangler's output.
    lines.append(
        f"SELECT name, source_type, source_tier FROM companies WHERE name IN ({names}) "
        "ORDER BY name;"
    )
    return "\n".join(lines) + "\n"


def main() -> None:
    if len(sys.argv) < 2 or sys.argv[1] not in ("check", "sql"):
        sys.exit(__doc__)
    if sys.argv[1] == "check":
        sys.exit(asyncio.run(check(load(set(sys.argv[2:])))))
    if len(sys.argv) != 3:
        sys.exit("usage: python scripts/apply_sources.py sql out.sql")
    Path(sys.argv[2]).write_text(sql(load(set())))
    print(f"wrote {sys.argv[2]}")


if __name__ == "__main__":
    main()
